; ==============================================================================
;
; Fix for the 2-pipe architecture for zcat:
; - 1. Reads itself (from argv[0] or stdin)
; - 2. Discards the first 512 bytes (skips the header/loader)
; - 3. Sends the remainder to zcat via pipe
; - 4. Reads the unpacked output from zcat and loads it into an anonymous memfd
; - 5. Executes the code from the memfd
;
; Optimization #1:
; - Single pipe (input) with direct writing by design.
; - Do fork: child writes directly to MEMFD via dup2.
;
; Optimization #2:
; - Zero pipe is the highest efficient version.
; - Transparently supports argv[0] or STDIN, both.
;
; Parent:
; - open(argv[0])     → fd 3 (or stdin = 0)
; - memfd_create()    → fd 4
; - skip 512 bytes from fd 3 (read loop)
; - fork()
;
; Child:
; - dup2(fd 3, 0)  ; stdin = input (offset, already +512 bytes)
; - dup2(fd 4, 1)  ; stdout = memfd
; - execve("zcat", ["zcat", "-"], NULL)
;
; Parent:
; - waitpid(-1, ...)
; - execveat(fd 4, "", argv, envp, AT_EMPTY_PATH)
;
; ==============================================================================

BITS 32
org 0x08048000

; ==============================================================================
; ELF32 HEADER (Micro-Loader a 32-bit, Teeny ELF)
; ==============================================================================
elf_header:
  db 0x7F, 'ELF', 1, 1, 1, 0  ; e_ident (Magic, Class 32bit, Data LSB, Version)
  times 8 db 0                ; Padding for e_ident
  dw 2                        ; e_type (Executable)
  dw 3                        ; e_machine (Intel 80386)
  dd 1                        ; e_version
  dd main_start               ; e_entry (The starting point of our code)
  dd phdr - elf_header        ; e_phoff (Offset of the Program Header Table)
  dd 0                        ; e_shoff (No Section Header Table, saving bytes)
  dd 0                        ; e_flags
  dw 52                       ; e_ehsize (Size of this header)
  dw 32                       ; e_phentsize (Size of a Program Header entry)
  dw 1                        ; e_phnum (Only one segment needed)
  ;-----------------------------------------------------------------------------
  ; Many Linux kernel ELF parsers completely ignore these 6
  ; bytes when section offset e_shoff = 0, as in this case.
  dw 0, 0, 0                  ; Section info (zeroed out)
  ; Finally managed to suck more bits out from nowhere to rescue these six 0s

phdr:
  dd 1                        ; p_type (PT_LOAD - Segment to load)
  dd 0                        ; p_offset
  dd 0x08048000               ; p_vaddr (Virtual address in memory)
  dd 0x08048000               ; p_paddr
  dd file_end - elf_header    ; p_filesz (Size of the code within the file)
  dd bss_end - elf_header     ; p_memsz (Size of the code within memory)

  ;-----------------------------------------------------------------------------
  dd 7                        ; p_flags (R+W+X - Read, Write, and Execute)
  dd 0x1000                   ; p_align (Standard page alignment)

  ; Security-by-Design VS Security-by-Subtraction

  ; Because uzpexec contains no input parsing logic that could be corrupted and
  ; its fixed 512-byte read loop cannot be overflowed, the writeable-executable
  ; segment offers no exploitable attack vector.

  ; Since the loader immediately forfeits control through atomic fork() / exec()
  ; or execveat() transitions that never return, an attacker cannot redirect
  ; execution to modified code before the process image is replaced.

  ; An adversary who can already write to the process memory holds sufficient
  ; privileges to inject code via ptrace or mprotect on any standard binary,
  ; which means the R+W+X flag introduces zero additional risk.

  ; WRX is the least of your troubles, but uzpexec as obscenely-powerful tool.

; ==============================================================================
; upexec CODE (Execution starts here)
; ==============================================================================
main_start:
  ; This would be the main() in a C-language sourcemain_start
  ; Save original argv and calculate envp from the initial stack layout
  ; Stack: [argc] [argv[0]] ... [argv[N]] [NULL] [envp...]
  pop eax                       ; argc (was [esp])
  mov esi, esp                  ; ESI = argv
  lea ebp, [esi+eax*4+4]        ; EBP = envp (callee-saved!)

  ; 1. Checking argv[0] to open input (itself or stdin)
  mov ebx, [esi]                ; CVE-2021-4034, pre-5.18
  cmp byte [ebx], al            ; SIGSEGV kill the bug here
  jz .stdin                     ; Tiny can't cover LK bugs

  ; ----------------------------------------------------------------------------
  ; Seek the match between filename and argv[0] by teo 32-bits compares (-9b)
  ; ----------------------------------------------------------------------------
  push esi                      ; Save ESI (argv) on the stack

  mov esi, ebx                  ; ESI = argv[0] for lodsb
;_xor ah, ah
.seek_eos:
;_inc ah
  lodsb                         ; AL = *ESI++, by CPU
  test al, al                   ; Check for the EOS '\0'
  jnz .seek_eos                 ; - N: loop again
                                ; - Y: ESI points to \0

;_A defensive check but apparently ./a (argv[0] = "a\0") works properly, anyway
;_This imposes restriction on the converted ELF (not-script) name: abc\0 !xec\0
;_This restriction is acceptable and the consequences of a violation are near-0
;_Where "near-0" means: yet TODO an extensive argv[0] underflow investigation
;_cmp ah, 8                     ; this avoids underflow
;_jb .mismatch                  ; too short, to match

  lea esi, [esi-8]              ; ESI = last 8 byte argv[0]
  mov edi, filename             ; EDI = pattern "uzpexec\0"
  cmpsd                         ; compare "uzpe"  (dword #1)
  jne .mismatch
  cmpsd                         ; compare "xec\0" (dword #2)
  jne .mismatch

  pop esi
  jmp .stdin
.mismatch:
  pop esi
  ; ----------------------------------------------------------------------------

.not_uzpexec:
  ; 2. Try to open itself (embedded payload mode, only)
  xor ecx, ecx                  ; O_RDONLY
  push 5                        ; SYS_open
  pop eax
  int 0x80
; It will fail later, anyway
; test eax, eax
; js exit_error
  mov edi, eax                  ; EDI = input fd (opened file)

  ; 3. Skip the fixed 512-bytes initial block (!stdin, only self-read)
  mov ecx, buf
  mov edx, 512

.skip_loop:
  push 3                        ; SYS_read
  pop eax
  mov ebx, edi                  ; input fd
  int 0x80
  test eax, eax
  js exit_error
  jz exit_error                 ; Premature EOF
  sub edx, eax
  jnz .skip_loop
  jmp .memfd

.stdin:
  xor edi, edi                  ; EDI = stdin (0)

.memfd:
  mov ebx, filename             ; fd owner's name
  movzx edx, byte [ebx - filename + do_script]
                                ; EDX now holds the flag
  test dl, dl                   ; Is the script flag 0?
  jnz .do_script                ; - N: call the /bin/sh
                                ; - Y: exec an ELF binary
  mov eax, 356                  ; SYS_memfd_create
  push 1                        ; MFD_CLOEXEC
  pop ecx
  int 0x80
; It will fail later, anyway
; test eax, eax
; js exit_error
  mov [memfd], eax
  jmp .fork_now                 ; Try to fork

.do_script:
  ; We are using 2-bytes at the tiop of BSS buffer (buf) to save the 2 FDs
  push 42                       ; SYS_pipe
  pop eax
  mov ebx, buf                  ; EBX is pointing to a 2 words array in BBS
  push ebx                      ; Save in the stack *buf for later
  int 0x80                      ; Now buf[0] = read_fd, buf[4] = write_fd

.fork_now:
  ; 5. Do a fork without do any pipe (lighter fork)
  push 2                        ; SYS_fork
  pop eax
  int 0x80
  test eax, eax
  jz child                      ; If EAX == 0, go to child process

  ; ============================================================================
  ; PARENT PROCESS
  ; ============================================================================
parent:
  test dl, dl                   ; Is it ELF mode (0)?
  jz elf_mode                   ; - Y: standard waitpid execution
                                ; - N: spawn the alt. interpreter

  pop edx                       ; Retrieve the *buf from the stack

  ; It closes the useless pipe
  push 6                        ; SYS_close
  pop eax
  mov ebx, [edx+4]              ; write_fd
  int 0x80

  ; Attach the zcat STDOUT (fd:1) to the child STDIN (fd:0)
  push 63                       ; SYS_dup2
  pop eax
  mov ebx, [edx]                ; read_fd
  xor ecx, ecx                  ; 0 = stdin
  int 0x80

  ; ----------------------------------------------------------------------------
  ; Spawns a /bin/sh whose STDIN is piped to zcat, passing along original argvs
  push 11                       ; SYS_execve
  pop eax
  mov ebx, do_script            ; script interpreter

  ; Safeguard: if argc is 0 <-- No, the issue was argv=NULL, SIGSEGV solves
  ; Therefore the branch "no_args" would never traversed and can be removed

  ; In-place stack manipulation using ESP (argv is at [esp]):
  mov dword [esp], dual_dash    ; overwrite original argv[0] with "--"
  lea ecx, [esp - 8]            ; original arguments argv[1] ... [n]
  push dash_s                   ; pushing "-s"
  push ebx                      ; pushing on current argv[0] do_script

  ; basic operations for calling the execve()
  mov edx, ebp                  ; envp (intact from main_start)
  int 0x80
  jmp exit_error
  ; ----------------------------------------------------------------------------

elf_mode:
  ; The parent waits for the child (zcat) to finish decompressing
  xor ecx, ecx
  xor edx, edx
  xor ebx, ebx
  dec ebx                       ; -1
  push 7                        ; SYS_waitpid
  pop eax
  int 0x80

  ; Closes the initial input (no longer needed in the parent), if !stdin
  test edi, edi
  jz .execute                   ; From stdin has file openedmain_start
  push 6                        ; SYS_close
  pop eax
  mov ebx, edi                  ; Closes the opened file fd
  int 0x80

.execute:
  ; 6. Execution from the memfd, which now contains the entire unpacked binary
  ; Fix argv[0] to point to our custom name in filename
  ; mov eax, filename           ; Load address of filename string
  ; mov [esi], eax              ; Overwrite original argv[0]
  ; Clean restoration of the stack before execveat to avoid EFAULT
  mov eax, 358                  ; SYS_execveat
  mov ebx, [memfd]              ; EBX = validated memfd
  push 0                        ; push empty string "" to the stack
  mov ecx, esp                  ; ECX = points to ""
  mov edx, esi                  ; EDX = intact original argv
  mov esi, ebp                  ; ESI = envp (extracted from EBP)
  mov edi, 0x1000               ; EDI = AT_EMPTY_PATH flag
  int 0x80                      ; Invoke Linux kernel to replace process
  jmp exit_error                ; execve() never returns, and we catch here
                                ; previously unchecked errors for smaller code

; ============================================================================
; CHILD PROCESS
; ============================================================================
child:
  ; 1st dup2: Connect input (edi) to STDIN (0) for both modes
  push 63                       ; SYS_dup2
  pop eax
  mov ebx, edi                  ; input fd (file or 0)
  xor ecx, ecx                  ; 0 = stdin
  int 0x80                      ; ECX remains 0 on return

  ; Select the correct output descriptor based on mode
  mov ebx, [memfd]              ; Default: assume ELF mode destination
  test dl, dl                   ; Is it ELF mode (0)?
  jz .do_stdout                 ; - Y: skip to stdout redirection
  mov ebx, [buf+4]              ; - N: overwrite with pipe write_fd

.do_stdout:
  ; 2nd dup2: Connect selected output (ebx) to STDOUT (1)
  push 63                       ; SYS_dup2
  pop eax
  inc ecx                       ; 1 = stdout (incremented from 0)
  int 0x80
  test eax, eax                 ; Catch deferred memfd/pipe errors here
  js exit_error

  ; Clean execution of simple zcat (zcat -)
  push 11                       ; SYS_execve
  pop eax
  mov ebx, zcat_path
  push 0
  push dash_args
  test edi, edi                 ; Are we reading from STDIN (edi == 0)?
  jnz .pure_zcat                ; No, it is a file, then skip '-f' push
  push force_arg

.pure_zcat:
  push zcat_path
  mov ecx, esp
  xor edx, edx
  int 0x80

  ; ============================================================================
exit_error:
; test ebx, ebx
; jnz exit_now

  ; Print copyright notice, version and internal name
  push zcat_path - copy_vers    ; bytes to write
  pop edx
  mov ecx, copy_vers
  mov byte [ecx + edx - 1], 10  ; line feed
  push  4                       ; SYS_write
  pop eax
  push  2                       ; stderr
  pop ebx
  int 0x80

; exit_now:
; xor ebx, ebx
; inc ebx                       ; Exit code 1
  push 1
  pop eax
  int 0x80

; ==============================================================================
; COMPACT DATA SECTION (appended to code)
; ==============================================================================
; filename can be changed by sed up to 7 chars + ending \0
