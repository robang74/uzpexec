; Input: EAX = magic number letto dal file (primi 4 byte)
; Output: ESI = puntatore a stringa "/bin/...cat\0" trovata
;         ZF = 1 se trovata, 0 se fallback

find_decompressor:
    mov ecx, magic_count
    mov esi, magics
    mov edi, paths

.loop:
    cmp eax, [esi]
    je .found
    add esi, 4
    add edi, 16
    loop .loop

    mov eax, catcmd         ; fallback
    ret

.found:
    mov eax, edi            ; EAX = stringa trovata o fallback
    ret

